#ifndef INC_PARTYMODE_H_
#define INC_PARTYMODE_H_


#include "global.h"
#include "params.h"

// 宴会芸モード。ジャイロで向きを保ち、床(板など)を回されても同じ方向を向き続ける。
// 手をかざして離す → ジャイロのゼロ点を測り直す → 向きを保つ → ボタンで止める、を繰り返す。
// 向き(ジャイロ)に加えて、前後の位置(左右の車輪の平均で測った距離)も保つ。
// 位置は車輪で測っているので、床ごと動かされたときは床に対して元の位置へ戻ろうとする
// (回す中心と機体の中心がずれていると、回すたびに車輪が少し前後に動く)。
// ログは手かざしで始めたときから、ボタンで止めるまで SD へ流し続ける(party/hold_NNNN.bin)。
// 長く回せば、走りながら SD へ流す仕組みの確かめにもなる(10 秒ごとに途中経過を UART に出す)。
// 電源を切るまで戻らない。
void PartyMode_Run(void);

#endif
