#ifndef INC_SLALOMTEST_H_
#define INC_SLALOMTEST_H_


#include "global.h"
#include "params.h"

// スラローム(小回り 90°・大回り 90°・大回り 180°)の試験(床上、壁の制御なし)。ログを貯める用。
// 走る前に、旋回の種類と向き(s90r / s90l / l90r / l90l / l180r / l180l)をボタンのクリックで切り替えて選び、
// 左と後ろに壁がある区画に北向きで置いて、手かざしで走り出す。尻当て(start_sequence)で真ん中にそろえてから
//   小回り 90°  : 半区画 + 1区画 → 前のオフセット → 曲がる → 後ろのオフセット → 1区画 + 半区画で止まる(縦3・横2区画)
//   大回り 90°  : 1区画(次の区画の中心) → 曲がる(斜め隣の中心) → 1区画で止まる(縦3・横3区画)
//   大回り 180° : 1区画(次の区画の中心) → U ターン(隣の列の中心) → 1区画で止まる(縦3・横2区画)
// を1回走る。Loggerに記録し、SDがあれば <種類>_NNNN.bin で保存してすぐ次を選べる
// (SDに保存できなかったときだけ、ボタンでPCへ送る)。電源を切るまで戻らない。
void SlalomTest_Run(void);

// 小回り(s90)の連続の試験。速さを選んだ範囲で SPEED_SELECT_SLALOM_TEST_V_MM_S の順に上げながら、各速さで
// 右と左を SLALOM_SWEEP_REPEAT 往復する。A(西と南に壁)に北向きに置いて手かざしで始めると、右の試験で
// B(A から東へ2・北へ2区画。東と南に壁)の真ん中で東向きに止まり、180° 回って左の試験で A に戻り、180° 回って…を
// くり返す(置き直さない)。出口の直線の両側に壁があると横のずれを測れる。1回ごとに SD に s90r / s90l で保存する。
// 打ち切り・電池の低下・すべて終わったときは、その時の速さの番号を LED の棒グラフで点滅させて止まる。
// 電源を切るまで戻らない。
void SlalomSweep_Run(void);

#endif
