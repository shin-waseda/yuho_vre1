// 小回りの滑りを止めて測る試験(TEST の SLIP。2026-11-06)。
// 迷路(4×4 の中。x 東、y 北。S = (0,0) で北向き、後ろの壁に付けて置く):
//   T1: S → (0,1) で右へ小回り → (1,1) の東の端で止まる((2,1) の東の壁の 186mm 手前)
//   T2: S → (0,1) で右へ小回り → (1,1) で左へ小回り → (1,2) の北の端で止まる((1,3) の北の壁の 186mm 手前)
//   要る壁: S の南、(2,1) の東、(1,3) の北。(0,1) の東、(1,1) の東と北、(1,2) と (1,3) の間は空けておく
// 止まる所は FW の「壁を読む所」と同じで、止まってから 0.5 秒前壁を読む(LOG_EV_SLIP_POINT / POINT2 と UART)。
// 最初に 1 TURN / 2 STRAIGHT を選ぶ。
//   TURN: 速さ 300 / 400 / 500 / 600 の順に、T1 と T2 を交互に各 SLIP_RUNS_EACH 本走る。
//   STRAIGHT: 同じ止まる所の壁を曲がらずに読む(2026-11-06 に足した)。E を 300 / 500 で各 SLIP_RUNS_EACH 本、続けて N を同じように。
//     E: (0,1) で東向き(西の外周の壁に付ける)→ まっすぐ (1,1) の東の端(T1 と同じ所)
//     N: (1,0) で北向き(南の外周の壁に付ける)→ まっすぐ (1,2) の北の端(T2 と同じ所)。(1,0) と (1,1) の間は空けておく
//     T1 − E、T2 − N で、曲がって生まれた前後のずれ(速さによらない分も含む)が出る。
//   PIVOT: 超信地旋回のずれ(2026-11-06 に足した)。T1・P1・T2・P2 を 300 / 500 で交互に各 SLIP_RUNS_EACH 本。置き方は全部 S。
//     P1: S → (0,1) の真ん中で止まり、右へ 90° 超信地旋回(探索の 180° の半分と同じく、前後を合わせてから回り、回った後も合わせる)
//         → (1,1) の東の端(T1 と同じ止まる所)
//     P2: P1 と同じく回ってから、(1,1) で左へ小回り → (1,2) の北の端(T2 と同じ止まる所)
//     P1 − T1 で超信地旋回の前後のずれ、P2 − T2 で横のずれが出る(小回りのずれは SLALOM_PRE/POST_ADJ_MM で打ち消してある)。
//   LR: 左右と回る中心のずれ(2026-11-06 に足した)。速さ 300 で、次の 11 種類を順に SLIP_RUNS_EACH 回くり返す(33 本)。
//     S に置く: T1 P1 T2 P2 / (2,0) 北向き(南の外周に付ける)に置く: T1L P1L T2L P2L / E / EW / N
//     T1L: (2,1) で左へ小回り → (1,1) の西の端(前壁は西の外周)。P1L: (2,1) の真ん中で左へ超信地旋回 → 同じ所。
//     EW: (2,1) で西向き((2,1) の東の壁に付ける)→ まっすぐ同じ所。T2L・P2L: 左の後 (1,1) で右へ小回り → (1,2) の北の端。
//     小回りは手で足す調整を引いた形で走る(回る中心のずれの式で、調整の入っていない小回りと超信地旋回を比べるため)。
//     (2,0) と (2,1) の間、(2,1) と (1,1) の間、(1,1) と (0,1) の間も空けておく。
// 1 本ごとに手で S に置き直し、手をかざして走らせる(自動で戻って押し当てる形は、フェイルセーフが働いたり、
// 向きと横の位置がそろわなかったりしたのでやめた)。
// 横壁追従は切り、横のずれの FB は入れる(ジャイロとエンコーダだけで軌道に沿わせる)。
// 解析は 300 の走りを基準にして、速い走りとの差で滑りを読む(壁の反射や置き方の約束のずれを消す)。
void SlipTurnTest_Run(void);

