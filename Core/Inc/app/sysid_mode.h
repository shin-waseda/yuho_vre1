#ifndef INC_SYSID_MODE_H_
#define INC_SYSID_MODE_H_

#include "global.h"
#include "params.h"

// 同定の実験(10-27 の実験計画書の E0/E1/E2)のモード。
// 走る前に条件を1回だけ選び(E1/E2: 電圧の FROM・TO、往復の回数、T_acc。E0: 並進か旋回か、往復の回数)、
// あとは「置いて手をかざす → 1本走る → 止まったら置き直す」をくり返すと、次の条件へ自動で進む。
// 条件の並び: 電圧ごとに「前進 → 後退」(E2 は「左回り → 右回り」)を回数ぶん。E0 は「+ → −」を回数ぶん。
// 手かざしの代わりにボタンを押すと、1本前に戻る(失敗した1本をやり直す)。
// 1本ごとに別のファイル(SD の sysid/<条件>_NNNN.bin)に 1kHz で流して記録する。列は SysidDebug(app/sysid_loop.h)。
// 全部終わったら1本目に戻る。電源を切るまで戻らない。
//
// E2S(超信地旋回の階段): 床か浮かせるか(浮かせたらファイル名が e2sl_)、電圧の FROM・TO(SYSID_STAIR_MV)、T_acc、回数を選ぶ。1回の手かざしで、電圧ごとに
// 「左回りのステップ → 右回りのステップ」を FROM から TO まで続ける(各ステップは止めてから SYSID_REST_MS 休んで次へ)。
// 階段1つが1本(1ファイル)で、回数ぶん手かざしする。ログの step 列が何番目のステップか(1 始まり)。
//
// E1S(前進のステップ): 電圧の FROM・TO(SYSID_E1S_MV)と T_acc を選ぶ。手かざし1回で1つの電圧の前進を1ステップ
// (+V を T_acc → 0V で止まるまで → SYSID_REST_MS 休む)走る。手で元の場所に戻して手かざしすると次の電圧へ進む。
// 1周(FROM〜TO)を1つのファイル sysid/e1s_<FROM>_<TO>mv_NNNN.bin にする(置き直している間は記録を止め、
// time_s はその間を数えない)。周の最後の1本の後に閉じる。ログの step 列が何番目の電圧か(1 = FROM)。
// 手を離してから走り出すまでの1秒(6軸の測り直しを含む)も記録する(seg −1、step 0。その直後のステップの前の止まっている区間)。
// 区間0(50ms)はファイルの始まりの1本目だけ。2本目からは区間1から始める。
// 途中で電源を切ると、ファイルは閉じられない(中身が読めない場合がある)。
// 中止(距離・速度・角度・止まらない。SYSID_E1S_ABORT_* と SYSID_STOP_TIMEOUT_MS)したら、ファイルを閉じて周の残りを飛ばし、
// 1本目(FROM)に戻る。
// 最初に PLACE(1 床、2 浮かせる)を選ぶ。浮かせたら(ファイル名 e1sl_)置き直しが要らないので、1回の手かざしで FROM から TO まで
// 1ステップずつ(SYSID_E1S_INC_V 刻み)続ける(1回の手かざしが1ファイル)。step 列が何番目の電圧か(1 = FROM)。
// 浮かせたときの中止は車輪の速さ(SYSID_ABORT_WHEEL_MM_S)と止まらない(SYSID_STOP_TIMEOUT_MS)だけで、中止したら残りの段を飛ばす。

typedef enum {
    SYSID_E0 = 0,  // 動き出しの電圧
    SYSID_E1 = 1,  // 並進のステップ
    SYSID_E2 = 2,  // 超信地旋回のステップ
    SYSID_E2S = 3, // 超信地旋回の階段
    SYSID_E1S = 4, // 前進のステップを、手かざしごとに電圧を上げて
    SYSID_E1V = 5, // 同定したモデルの FF だけで走る検証(SYSID_E1V_*)
    SYSID_E1B = 6, // 減速の同定: FF で加速 → 一定 → 一定の電圧のブレーキ(SYSID_E1B_*)
    SYSID_E1T = 7, // 旋回の同定: 走りながら左右の差をステップで入れる(SYSID_E1T_*)
    SYSID_E1K0 = 8, // V_d = 0 で走ったときの曲がり具合 κ₀(SYSID_E1K0_*。走り方は E1T と同じ)
    SYSID_E1W = 9,  // b_ω を V_d の跳びで測る(SYSID_E1W_*。走り方は E1T と同じ)
} SysidTest;

void SysidMode_Run(SysidTest test);

#endif
