// ============================================================
// 機体寸法・エンコーダ換算
// エンコーダはモーター軸に付いているので、タイヤ1回転あたりの
// カウント数 = モーター1回転のパルス数 × 逓倍 × 減速比。
// ============================================================

// ノギスでの実測は 23.35。直進 1080mm を 300mm/s と 800mm/s で走らせると、どちらも
// ログの距離より約2%(21〜22mm)行き過ぎた(2026-10-07)。速さによらないので滑りではなく
// 換算のずれとして、23.35 × 1102 / 1080.8 にした(実際に転がる実効的な直径)。
#define WHEEL_DIAMETER_MM      23.81f

#define ENCODER_PPR        4096.0f // FAULHABER IEH2-4096: モーター1回転あたり
#define ENCODER_MULTIPLIER 4.0f    // TIM4/TIM8 = TIM_ENCODERMODE_TI12 (A/B両エッジで4逓倍)
#define GEAR_PINION_T      13.0f   // M0.5 (divergence_v3と同じ)
#define GEAR_SPUR_T        42.0f   // M0.5

// タイヤ1回転あたりのカウント数 (≈52935)
#define ENCODER_PULSES_PER_REV (ENCODER_PPR * ENCODER_MULTIPLIER * GEAR_SPUR_T / GEAR_PINION_T)

#define MM_PER_PULSE ((3.14159265f * WHEEL_DIAMETER_MM) / ENCODER_PULSES_PER_REV)

// エンコーダの取り付け向きにより、パルス増加方向と前進方向が
// 逆転する場合に-1.0fへ反転させる。
#define ENCODER_L_SIGN 1.0f
#define ENCODER_R_SIGN -1.0f

// 左右タイヤの実効的な間隔[mm]。車輪の速度差 ↔ 機体の角速度 の換算に使う(kinematics.c)。
// 設計上の値は 57.90。超信地旋回のログ(2026-10-06)で、ジャイロの角速度が
// (vr - vl) / 57.90 の 0.912 倍だったので、実際に回る量に合わせて 57.90 / 0.912 にした。
// (タイヤの接地点のずれや横滑りを含む値。PIVOT のログを何回か取って確かめること)
// その後 WHEEL_DIAMETER_MM を約2%大きくした(23.35 → 23.81)ので、車輪の速度も2%大きく出る。
// ジャイロとの関係を保つため、同じ割合で 63.50 × 23.81 / 23.35 にした。
#define TREAD_WIDTH_MM 64.75f

// ============================================================
// 制御周期
// TIM6: Prescaler=84-1, Period=1000-1 → 84MHz/84/1000 = 1kHz
// ============================================================

#define CONTROL_DT_S 0.001f

// ============================================================
// 速度制御 (2自由度制御: FF + PID)
// 出力はモーター電圧[V]。duty = 電圧 / バッテリー電圧 でPWMへ変換するので、
// 電池電圧が下がってもゲインの効き方が変わらない。
//   電圧 = FF_FRIC × sign(目標速度)   (クーロン摩擦。速度によらず一定)
//        + FF_GAIN × 目標速度         (速度に比例する分)
//        + FF_ACC  × 目標加速度       (加速に要る分)
//        + PID(目標 - 実速度)         (外乱・モデル誤差の補正)
// FFは目標だけから計算し、実測を通さない(2自由度制御)。
// Kp/Kiは、PWM単位で調整した値(Kp=5, Ki=20 [PWM/(mm/s)])を
// Vbat≈7.9V (1V≈531.5PWM) で換算したもの。
// ============================================================

// その後、FF と位置・向きの制御を入れてから VEL_PID のステップ(床上、外側の制御なし)で見直した
// (2026-10-07)。0.0094 では立ち上がりの間に I 項が 0.19V 溜まり、20% 行き過ぎて 0.3 秒かけて
// 戻っていたので、P を強めて立ち上がりを P に受け持たせる(KI はそのまま)。
#define VELOCITY_KP 0.015f  // [V/(mm/s)](以前は 0.0094)
#define VELOCITY_KI 0.0376f // [V/(mm/s)/s]
#define VELOCITY_KD 0.0f

#define VELOCITY_PID_OUTPUT_MIN -BATTERY_FULL_V // [V] 対称(マイナス側=後退/ブレーキ方向)
#define VELOCITY_PID_OUTPUT_MAX  BATTERY_FULL_V

// 速度FF。この機体は左右の駆動系の重さが違うので左右で分ける。すべて床上の値。
// 定常走行時の電圧を2つの速度で測り、直線 電圧 = FRIC + GAIN × 速度 で近似した:
//   左: 0.47V @200mm/s, 0.55V @300mm/s / 右: 0.51V @200mm/s, 0.56V @300mm/s
// 微調整は定常時のI項を見る(I項が0付近になれば合っている)。
// 右は直進のログ3回(2026-10-06〜07)で巡航中のI項が 0.30 / 0.18 / 0.15V と正のままだったので、
// 0.41V から 0.12V 上げた。
// その後、右の車軸のねじを締め直したら右の駆動系が軽くなり(2026-10-07)、巡航中の I 項が
// −0.37V になったので、その分下げた。駆動系の摩擦は組み立てで大きく変わるので、
// 分解やぶつけた後は I 項を見て合わせ直すこと。
#define VELOCITY_FF_FRIC_L 0.32f     // [V]
#define VELOCITY_FF_FRIC_R 0.16f     // [V]
#define VELOCITY_FF_GAIN_L 0.00075f  // [V/(mm/s)]
#define VELOCITY_FF_GAIN_R 0.00050f  // [V/(mm/s)]

// 加速度FF係数[V/(mm/s^2)]。
// 台形プロファイル(±2000mm/s^2)の加速中・減速中の電圧から、摩擦と速度の分を
// 引いて加速度で割り、加速・減速の平均を取った値(摩擦の影響が打ち消される)。
// その後、加速を 2000/3000/4000mm/s^2 に上げたログ(2026-10-07)で、加速中の I 項が
// 0.03/0.05/0.09V と加速度に比例して正だった(4000で約10%足りない)ので、10%上げた。
// (減速中は左だけ I 項が負 = 多すぎる傾向がある。加速と減速で分けるかは未定)
#define VELOCITY_FF_ACC_L 0.000275f
#define VELOCITY_FF_ACC_R 0.000275f

// 超信地旋回のときだけ足す摩擦FF[V]。各車輪が回る向きにかける。左右で分ける。
// 超信地旋回ではタイヤが横にこすれるので、直進用の FF(FRIC + GAIN × 速度)では足りない。
// PIVOT のログ(2026-10-06、約100mm/s)で、実際にかけた電圧が直進用の式より
// 0.75〜0.84V 大きかったので、まず左右とも 0.80V にした。
// その後のログで、右は I 項がほぼ 0(合っている)、左は I 項が −0.25V 前後で
// 目標の 1.15 倍ほど速く回っていた。左を 0.65V にすると I 項の符号が逆になった
// (少なすぎ)ので、0.80V と 0.65V のときの I 項から直線で補間して、I 項が 0 になる 0.70V にした。
// 速度に比例するのか一定なのかは未確認(角速度を変えたログで確かめる)。
// 位置の制御を入れ、直進用の VELOCITY_FF_FRIC_R を 0.12V 上げた後のログ(2026-10-07)で、
// 左右とも回る向きと逆の I 項(左 平均0.13V、右 平均0.11V)が出ていたので、その分下げた。
// その後のログで、左回り(反時計回り)は I 項がほぼ0になったが、右回り(時計回り)は I 項の符号が
// 逆になった(足りない)ので、回る向きでも分けた。右回りは、L 0.70/R 0.80 と L 0.57/R 0.69 の
// 2回のログの I 項から直線で補間して、I 項が0になる値にした。
// (右回りはいつも左回りの後に回しているので、順番の影響が混ざっている可能性はある)
#define PIVOT_FF_FRIC_CCW_L 0.57f // 左回り(反時計回り)
#define PIVOT_FF_FRIC_CCW_R 0.69f
#define PIVOT_FF_FRIC_CW_L  0.64f // 右回り(時計回り)
#define PIVOT_FF_FRIC_CW_R  0.76f

// ============================================================
// 角度・角速度の制御(車輪速度ループの外側)
//   ω_cmd = ω_ref + ANGLE_KP×(θ_ref − θ_gyro) + ANGULAR_KP×(ω_ref − ω_gyro)   [rad/s]
// θ_ref は目標の向き。制御を有効にした時点の向きから、プロファイルの角速度を積分して作る。
// 止まってもリセットしないので、旋回のたびの角度のずれが積み重ならない。
// 制御が有効な間は、止まっていても常に効かせる(振動が出たらゲインで調整する)。
// 角度の誤差は時定数 (1+ANGULAR_KP)/ANGLE_KP [s] で縮む(内側が十分速い前提)。
// 入れた時は、走行中の働きが以前の ω の PI(KP 0.5, KI 15)と同じになるようにしていた(その後 ANGLE_KP を変更)。
// GYRO_Z_SIGN が正しいことを先に確認すること(逆だと正帰還になり回り出す)。
// ============================================================

#define ANGULAR_CONTROL_ENABLE 1     // 0にすると補正なし(比較試験用)
#define ANGULAR_KP 0.5f              // 角速度の P [-]
// 15(以前の角速度の KI と同じ働き)では、超信地旋回で FF の足りない分を受けるのに 2〜3° のずれが
// 必要だった(2026-10-07、VELOCITY_KP を 0.015 にした後)。止まった後に揺れがなかったので 25 にした。
#define ANGLE_KP   25.0f             // 角度の P [1/s]
#define ANGULAR_CORR_LIMIT_RAD_S 6.0f // 補正量の上限[rad/s](約340dps)

// ============================================================
// 位置の制御(車輪速度ループの外側、並進方向)
//   v_cmd = v_ref + POSITION_KP×(s_ref − s)   [mm/s]
// s は進んだ距離(左右の車輪の平均速度を積分したもの)、s_ref は目標の距離。
// どちらも制御を有効にした時点を0とし、s_ref はプロファイルの速度を積分して作る。
// 角度と同じく、止まってもリセットせず、止まっている間も効かせる。
// 補正は車輪速度の目標に足すだけで、FF には入れない(FF はプロファイルの目標だけから)。
// 車輪速度ループの I 項だけでも位置のずれはゆっくり縮むが、止まる直前は静止摩擦に負けて
// ずれが残る(2026-10-07 のログで −4.5mm、そのとき右の I 項は約0.18V)。
// ============================================================

#define POSITION_CONTROL_ENABLE 1        // 0にすると補正なし(比較試験用)
#define POSITION_KP 10.0f                // [1/s](仮の値。位置のずれは時定数 約1/KP [s] で縮む)
#define POSITION_CORR_LIMIT_MM_S 200.0f  // 補正量の上限[mm/s]

// 迷路の1区画の長さ[mm]
#define SECTION_MM 180.0f

// 目標0かつ左右の実速度がこれ未満なら、PIDの積分を捨てて出力0にする。
// (摩擦で止まった後もI項が残り、PWMが出続けるのを防ぐ)
// 角度か位置の制御が有効なときは、止まっている間も向きと位置を保つので使わない。
#define VELOCITY_STOP_RESET_MM_S 20.0f

// 電圧→dutyの変換に使うバッテリー電圧の下限[V]。電池未接続時の0割り防止。
#define VELOCITY_VBAT_MIN_V 5.0f

