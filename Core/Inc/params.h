// 座標はスタート区画が(0, 0)、xが東、yが北へ増える。スタートでは北を向く。
// ============================================================

#define MAZE_SIZE 16 // 1辺の区画数(クラシック)

#define MAZE_START_X 0
#define MAZE_START_Y 0

// ゴール区画(クラシック16×16は中央の4区画)
#define MAZE_GOAL_MAX   9 // 登録できるゴール区画の最大数(3×3まで)
#define MAZE_GOAL_COUNT 4
#define MAZE_GOALS { { 7, 7 }, { 8, 7 }, { 7, 8 }, { 8, 8 } }

// Dijkstraのコスト。直進1区画あたりと、向きを変える分の上乗せ(BlueEyesと同じ値)。
// 旋回を高くするほど、曲がる回数の少ない経路を選ぶ。
#define MAZE_COST_STRAIGHT 1
#define MAZE_COST_TURN90   7
#define MAZE_COST_TURN180  50

// 探索の帰りに、4方向の壁がすべて分かっている区画へ入るときに上乗せするコスト。
// 大きいほど、まだ見ていない区画を通って帰ろうとする(帰りの距離は延びる)。
// 0にすると最短で帰る。値は tools/maze_sim で調整する(3は仮の値)。
#define MAZE_COST_KNOWN_CELL_RETURN 3

// ============================================================
// 探索走行 (app/search_run)
// 直進は止まらずに区画をつなぎ、区画の境界で壁を読む。曲がるときは区画の真ん中で止まって
// 超信地旋回し、次の境界まで半区画進む。
// ============================================================

#define SEARCH_V_MM_S           500.0f  // 直進の速さ(壁の判定・壁の制御を確かめたのは 300mm/s まで)
#define SEARCH_ACCEL_MM_S2      2000.0f // 加速度・減速度(3000 では真ん中で止まる減速が強すぎて安定しなかった)
#define SEARCH_TURN_OMEGA_DPS   180.0f  // 超信地旋回(PIVOT の試験と同じ)
#define SEARCH_TURN_ALPHA_DPS2  1800.0f
#define SEARCH_TURN_WAIT_MS     100     // 真ん中で止まってから回るまで・回ってから走り出すまでの待ち
#define SEARCH_GOAL_WAIT_MS     1000    // ゴールで止まっている時間
#define SEARCH_STEP_TIMEOUT_MS  5000    // 1つの動きがこれを過ぎても終わらなければ打ち切る
// 壁を読んで次の動きを決める位置を、境界のこれだけ手前にする[mm](0 なら境界で読む。2026-10-08 までの動き)。
// スラロームの前壁補正の範囲(曲がり始め ± SLALOM_FRONT_WINDOW_MM)の手前の端は、曲がり始めが境界から約 6mm 先なので
// 境界の約 9mm 手前になる。そこより前に「曲がる」と決めておかないと範囲の手前側が使えないため、経路の計算
// (最大 3ms ≒ 1.5mm)と余裕を足して 12mm にした。探索のログ 56 回で、境界と 11mm 手前で壁の判定が変わる回はなかった
// (閾値までの余裕の最小: 左 54、右 96、前 13)。
#define SEARCH_WALL_READ_BEFORE_MM 12.0f

// 尻当て(BlueEyes の set_position と同じ使い方)。後ろの壁に押し当てて向きと位置をそろえ、
// 真ん中まで進む。スタート(start_sequence)、途中の180°、ゴールと終わりの180°で使う。
#define SEARCH_SETPOS_BACK_V_MM_S  100.0f // 後ろへ下がる速さ
#define SEARCH_SETPOS_BACK_MS      1200   // 下がる時間(真ん中から壁まで約40mm を下がり、残りは押し当てる。800 では短かった)
#define SEARCH_SETPOS_SETTLE_MS    100    // 押し当てた後、モーターを止めて待つ時間
#define SEARCH_SETPOS_FRONT_MM     40.0f  // 壁に当たった所から真ん中までの距離(探索のログで、真ん中から壁まで 39〜40mm 下がった)

// 探索・最短走行のログ。走りながら SD へ流し続ける(logger の Logger_Stream*。止まらずに記録できる)。
// 24KB のブロック2つを交互に使う。15列・5ms ごとなら、1ブロックは約 2 秒ぶんで、SD が待たせても
// 2 秒までは行を捨てずに済む(SD の書き込みは最大 0.6 秒ほど待たされたことがある)。
#define SEARCH_LOG_DECIMATION      5      // 5 tick(5ms)に1回記録する
#define SEARCH_LOG_SAVED_LIGHT_MS  500    // 走り終わってファイルを閉じられたら、直結の LED を全部点ける時間

// 最短走行(app/search_run の FastRun)。続く直進をまとめてこの速さで走り、曲がるときは真ん中で
// 止まって超信地旋回する(旋回は探索と同じ SEARCH_TURN_*)。
#define FAST_V_MM_S             800.0f  // 直進の最高速度(STRAIGHT で 800mm/s は確かめた)
#define FAST_ACCEL_MM_S2        2000.0f // 加速度・減速度(探索で安定した値)

// 走る前に選べる速さ(モードを決めた直後に、右タイヤを回して選びボタンで決める。電源を切るまでそのまま)。
// 最初に表示するのは、上の SEARCH_V_MM_S / FAST_V_MM_S / PIVOT の試験の値に一番近いもの。項目は 15 個まで。
// 探索・STRAIGHT の試験・SLALOM の試験(小回り)の直進の速さ。小回りは曲がるときもこの速さで、
// 角速度は速さに比例、角加速度は速さの2乗に比例させる(SLALOM_* は SLALOM_V_MM_S のときの値。
// 曲がる形・前後のオフセット・前壁補正の位置は速さによらず同じになり、横加速度は速さの2乗で増える)。
#define SPEED_SELECT_SEARCH_V_MM_S   { 300.0f, 400.0f, 500.0f, 600.0f }
// 最短走行の直進の最高速度(曲がるときの速さは SLALOM_* / FAST_LARGE* のまま)
#define SPEED_SELECT_FAST_V_MM_S     { 600.0f, 800.0f, 1000.0f, 1200.0f }
// PIVOT の試験の最高角速度(角加速度は試験の値のまま)
#define SPEED_SELECT_PIVOT_OMEGA_DPS { 180.0f, 360.0f, 540.0f }

// 最短走行の大回り(SMALL は探索と同じ SLALOM_* の小回り)。前後のオフセットは logic/control/slalom が
// 計算する(*_ADJ はそこからの調整分)。どれも仮の値で、まず横加速度を小回りより小さめにしてある。
// 大回り 90°: 区画の中心 → 斜め隣の区画の中心。600mm/s・230dps・3000dps² でオフセット約 7mm、横加速度約 0.25G。
#define FAST_LARGE90_V_MM_S       600.0f
#define FAST_LARGE90_OMEGA_DPS    230.0f
#define FAST_LARGE90_ALPHA_DPS2   3000.0f
#define FAST_LARGE90_PRE_ADJ_MM   0.0f
#define FAST_LARGE90_POST_ADJ_MM  0.0f
// 大回り 180°: 区画の中心 → 隣の列の区画の中心(柱を回る U ターン)。横にちょうど1区画移るよう、
// 最高角速度は起動時に計算で決める(500mm/s・3000dps² で約 330dps、横加速度約 0.3G の見込み)。
#define FAST_LARGE180_V_MM_S      500.0f
#define FAST_LARGE180_ALPHA_DPS2  3000.0f
#define FAST_LARGE180_PRE_ADJ_MM  0.0f
#define FAST_LARGE180_POST_ADJ_MM 0.0f

// ============================================================
// スラローム(小回り 90°、探索用)
// 並進の速さを保ったまま、角速度を台形(角加速 → 一定 → 角減速)で動かして 90° 曲がる。
// 曲がる前後の直進(オフセット)は、区画の境界の真ん中から曲がり始め、隣の境界の真ん中で
// 曲がり終わるように logic/control/slalom が計算する(PRE/POST_ADJ はそこからの調整分)。
// 500mm/s・450dps・8000dps² で、オフセットは前後とも約 12mm、横加速度は約 0.4G(計算値)。
// 2026-10-08 に ADJ を入れた: 探索・最短走行のログ 200 回(壁切れ補正・前壁補正の記録)で、小回り1回のずれを
// 合わせると、出口の向きに 8〜12mm 遅れ、外へ 5〜7mm ずれていた(右左ほぼ同じ。外へのずれは横のセンサーで
// 直接見ても +2〜+6mm)。外へのずれはスリップ(K≈0.02)で説明できるが、前後の遅れはその分(約 4.5mm)より大きく、
// 残りの原因は未確認。遅れる分だけ後ろを長く、外へずれる分だけ前を短く(早く曲がり始める)する。
// 500mm/s での値。速さや電池の電圧で変わるかもしれない。
// ============================================================

#define SLALOM_V_MM_S          SEARCH_V_MM_S // 曲がるときの並進の速さ(探索の直進と同じ。探索では止まらずに曲がるため)
#define SLALOM_OMEGA_DPS       450.0f  // 最高角速度
#define SLALOM_ALPHA_DPS2      8000.0f // 角加速度
#define SLALOM_PRE_ADJ_MM      -6.0f   // 前のオフセットの調整分(+ で長く)。外へ約 6mm ずれる分、早く曲がり始める
#define SLALOM_POST_ADJ_MM     10.0f   // 後ろのオフセットの調整分(+ で長く)。出口の向きに約 10mm 遅れる分、長く進む

// スラロームの前壁補正(探索の小回り)。曲がる区画の奥に壁があるとき、距離で決めた曲がり始めの位置の
// 前後 SLALOM_FRONT_WINDOW_MM の間で、FL + FR が SLALOM_FRONT_REF_SUM に届いた瞬間に曲がり始める
// (届かなければ、範囲の終わりで曲がり始める)。
// REF_SUM は「正しい曲がり始めの位置(入口の境界 + 前のオフセット)で見える FL + FR」。境界に止めて測った値は
// FL 240 + FR 127 = 367(2026-10-07、前に壁あり)で、それより 12mm 前なので少し大きいはず(はじめは仮に 400)。
// 2026-10-08: 一度 420 にしたが 400 に戻した。420 は「位置を直した直後の回で、400 に届いたのが 4mm 手前」からの
// 見積もりだったが、その 4mm の大部分は壁切れ補正の偏り(壁切れ補正の後は機体が約 4mm 前にいる)だった。
// 壁切れ・スラロームのずれも一緒に合わせたモデル(探索・最短走行のログ 154 回)では、曲がり始めのずれは
// 400 のとき +0.9mm、420 のとき +3.5mm(遅い)で、400 がほぼ合っている。
// (境界に止めて測った 367 から 12mm 先として見積もると 420 になるが、ログとは合わない。止めて測ったときの
//  前の壁までの距離や置き方が、走っているときと違った可能性がある。未確認)
// 同じ日に 373 へ: SLALOM_PRE_ADJ_MM(−6mm)で曲がり始めの位置が 6mm 手前になったので、その位置で見える値に合わせた
// (FL+FR は 1mm あたり約 4.5 なので 400 − 6 × 4.5 ≒ 373)。閾値を変えないと、前壁補正が元の位置で曲がり始めてしまう。
#define SLALOM_FRONT_ENABLE    1
#define SLALOM_FRONT_REF_SUM   373
#define SLALOM_FRONT_WINDOW_MM 15.0f

