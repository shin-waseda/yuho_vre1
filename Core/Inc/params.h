// ============================================================
// 壁の判定 (logic/wall_sense)
// 区画の境界で壁センサーの値を読み、しきい値を超えたら壁ありとする。
// 値は IR 点灯 − 消灯の差。左右のセンサー(L/R)は斜め前を向いている。
// 境界に止めて測った値(2026-10-07、ばらつきは ±1 程度):
//   左右に壁あり: L 318 / R 276(このとき前に壁がなくても FL 48 / FR 36。横の壁の反射が入る)
//   左右に壁なし: L 43 / R 33 / FL 13 / FR 6
//   前に壁あり  : FL 240 / FR 127
// しきい値は「壁なしの最大」と「壁ありの最小」の真ん中にした。
// 前の壁は FL と FR の合計で見る(FR は壁ありでも小さく、機体が少し斜めでも合計はあまり変わらない)。
// 走りながら境界で読んだ値は未確認(止めて測った値なので、走行のログで確かめること)。
// ============================================================

#define WALL_TH_L          180 // 左の壁(L)
#define WALL_TH_R          150 // 右の壁(R)
#define WALL_TH_FRONT_SUM  220 // 前の壁(FL + FR)

// ============================================================
// 壁の制御 (logic/control/wall_control)
// 直進中、左右の壁センサーの値が基準(真ん中にいるときの値)からずれた分に比例して、
// 迷路の軸の向きから少し向きをずらす(横のずれを真ん中へ戻す向きにする)。
//   誤差 = (L − REF_L) − (R − REF_R)   (片側だけ使えるときは、その側の差の2倍。どちらもなければ0)
//   目標の向き = 迷路の軸の向き + オフセット、オフセット [deg] = −WALL_KP_DEG × 誤差
//   (誤差が正 = 左に寄っている → 右へ向ける)
// 横のずれが 0 に戻ればオフセットも 0 に戻るので、向きのずれが残らない。
// (以前は「誤差に比例して向きを回す速さ」にしていたが、大きく寄ったとき向きが 8.7° 回ったまま残り、
//  曲がった後に斜めのまま壁にぶつかった。2026-10-07 の探索のログ)
// 値は mm に直さず、センサーの値の単位のまま扱う(ゲインはログを見て合わせる)。
// 壁の切れ目や柱の横では値が急に変わり、「壁が遠い」と区別がつかないので、
// EDGE_STEP_MM 進むあいだの変化が EDGE_DIFF を超えた側は、EDGE_HOLD_MM のあいだ使わない。
// 走行のログ(2026-10-07): 切れ目では 5mm で 30〜170 変わり、寄っていくだけなら 5mm で 2 程度。
// ============================================================

#define WALL_CONTROL_ENABLE  1     // 0にすると壁の制御なし(比較試験用)
#define WALL_REF_L           312   // 真ん中にいるときの L(走行のログのスタート直後)
#define WALL_REF_R           282   // 真ん中にいるときの R
#define WALL_KP_DEG          0.03f // [deg / センサーの値](WALL_KP_REF_V_MM_S のときの値。仮。誤差100で3°)
// ゲインは速いほど弱くする: WALL_KP_DEG × WALL_KP_REF_V_MM_S / 速さ。
// 横に戻る速さは「速さ × オフセット」なので、こうすると真ん中に戻るまでの時間が速さによらず同じになる。
#define WALL_KP_REF_V_MM_S   500.0f // WALL_KP_DEG を合わせた速さ(探索の速さ)
#define WALL_KP_MIN_V_MM_S   100.0f // これより遅いときは、この速さとして計算する(遅いときに強くなりすぎないよう)
#define WALL_OFFSET_MAX_DEG  5.0f  // オフセットの上限[deg]
#define WALL_OFFSET_RATE_DPS 90.0f // オフセットを変える速さの上限[dps](壁が切れたときなどに向きが跳ばないように)
#define WALL_EDGE_STEP_MM    2.0f  // 値の変化を比べる間隔[mm](5mm では切れ目を見つけるまでに最大5mmぶん補正が漏れた)
#define WALL_EDGE_DIFF       15    // これを超えて変わったら、壁の切れ目・柱とみなす(2mm あたり)
#define WALL_EDGE_HOLD_MM    40.0f // 切れ目を見つけてから、その側を使わない距離[mm]

// ============================================================
// 壁切れ補正(進む方向の位置の補正。探索の1区画の直進と、最短走行の直進で使う)
// 直進中に横の壁がなくなった瞬間(L か R が WALL_TH_L/R を上から下へ切った瞬間)は、機体が区画の境界を
// WALL_EDGE_POS_L/R_MM 過ぎた所にいるはずなので、そこからずれていた分だけ、次の境界(目標の距離の基準)をずらす。
// 走行のログ(2026-10-07)では、壁が切れるのは境界を約 75〜82mm 過ぎた所だった。
// 2026-10-08 に左右で別の値にした: 探索・最短走行のログ 200 回で、スラロームのずれと一緒に合わせると、78mm に対して
// 右の壁切れは +5.3〜+5.5mm 遅く、左は −0.5〜−1.8mm だった(尻当ての直後に左右が続けて出た2回も 右 − 左 = +4.0mm)。
